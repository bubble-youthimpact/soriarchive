"""Rebuild assets/data.js from a Bubble CSV export.
Usage: python3 tools/build_data.py path/to/export.csv
"""
import csv, json, sys, pathlib
csv.field_size_limit(10**9)
ROOT = pathlib.Path(__file__).resolve().parent.parent
FIX_REGION = {"전라북": "전라북도", "경기인": "경기인천", "충청북": "충청북도", "충청남": "충청남도",
              "경상북": "경상북도", "경상남": "경상남도", "전라남": "전라남도", "강원": "강원도", "제주": "제주도"}
GENRES = [
  ("모심는 소리", "Rice Planting Song", "g-rice.avif"),
  ("베틀노래", "Weaving Song", "g-weaving.avif"),
  ("상여소리", "Funeral Procession Song", "g-funeral.avif"),
  ("자장가", "Lullaby", "g-lullaby.avif"),
  ("밭가는 소리", "Field Plowing Song", "g-plowing.avif"),
  ("방아소리", "Pounding Song", "g-pounding.avif"),
  ("소모는 소리", "Cattle Driving Song", "g-cattle.avif"),
  ("보리타작", "Barley Threshing Song", "g-barley.avif"),
  ("장타령", "Marketplace Chant", "g-market.avif"),
  ("뱃노래", "Boating Song", "g-boat.avif"),
]
# x / y = pin tip position on assets/img/korea-map.png, in % of the image
REGIONS = [
  ("강원도", "Gangwon", 62.9, 19.2),
  ("경기인천", "Gyeonggi · Incheon", 28.3, 22.8),
  ("경상남도", "South Gyeongsang", 71.4, 65.8),
  ("경상북도", "North Gyeongsang", 74.8, 43.8),
  ("전라남도", "South Jeolla", 23.4, 68.9),
  ("전라북도", "North Jeolla", 34.5, 57.4),
  ("제주도", "Jeju", 14.3, 94.2),
  ("충청남도", "South Chungcheong", 25.5, 42.8),
  ("충청북도", "North Chungcheong", 48.6, 37.2),
]
def clean(s): return (s or "").replace("\r\n", "\n").strip()
rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8-sig")))
sounds = []
for r in rows:
    region = clean(r.get("지역"))
    region = FIX_REGION.get(region, region)
    src = clean(r.get("출처"))
    if src.replace(" ", "") == "한국구비문학대계": src = "한국구비문학대계"
    title = clean(r.get("제목"))
    sounds.append({"r": region, "g": title, "t": title, "l": clean(r.get("가사")),
                   "d": clean(r.get("사투리 특징")), "c": clean(r.get("사회문화적 해석")),
                   "u": clean(r.get("음원")), "s": src})
data = {
  "genres": [{"id": a, "en": b, "img": "assets/img/" + c} for a, b, c in GENRES],
  "regions": [{"id": a, "en": b, "x": x, "y": y} for a, b, x, y in REGIONS],
  "sounds": sounds,
}
out = ROOT / "assets" / "data.js"
out.write_text("/* SoriArchive data — generated by tools/build_data.py from the Bubble export. */\nwindow.SORI = " +
               json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
from collections import Counter
print(len(sounds), "sounds"); print(Counter(s["r"] for s in sounds))
